// Helper functions
export function getFeaturedProjects(limit = 6): Project[] {
  return projects.filter((p) => p.featured).slice(0, limit);
}

export function getProjectById(id: string): Project | undefined {
  return projects.find((p) => p.id === id);
}

export function getSimilarProjects(project: Project, limit = 3): Project[] {
  return projects
    .filter(
      (p) =>
        p.id !== project.id &&
        (p.type === project.type || p.industry === project.industry)
    )
    .slice(0, limit);
}

export function getAllProjectSlugs(): string[] {
  return projects.map((p) => p.id);
}

export const allTechStacks: string[] = Array.from(
  new Set(projects.flatMap((p) => p.techStack))
).sort();

export const allIndustries: string[] = Array.from(
  new Set(projects.map((p) => p.industry))
).sort();
